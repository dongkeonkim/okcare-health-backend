-- 이메일 비교 규칙을 기능_명세의 정규화 범위와 맞춘다.
--
-- V1은 테이블 기본 콜레이션 utf8mb4_unicode_ci를 그대로 썼다. 이 콜레이션은 대소문자뿐 아니라
-- 악센트도 구분하지 않으므로 jose@example.com과 josé@example.com이 같은 값으로 취급된다. 그러면
-- 앞선 회원이 있을 때 뒤 회원의 가입이 409가 되고, 로그인 조회도 악센트가 다른 이메일에 걸린다.
-- RFC 기준으로 두 주소는 서로 다르고, 명세는 앞뒤 공백 제거와 소문자 정규화만 같은 값으로 본다.
--
-- 적용된 V1을 고치지 않고 전진 보정한다. Flyway가 checksum으로 V1을 고정하므로 수정은 기존
-- 데이터베이스의 validation을 깨뜨린다.
--
-- utf8mb4_0900_as_cs는 악센트와 대소문자를 모두 구분한다. 대소문자 구분이 문제되지 않는 이유는
-- 애플리케이션이 저장 전에 소문자로 정규화하기 때문이다. 컬럼만 바꾸고 테이블 기본 콜레이션은
-- 건드리지 않는다. 이름과 닉네임은 사람이 읽는 값이라 비구분 비교가 자연스럽다.
ALTER TABLE members
    MODIFY email VARCHAR(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_as_cs NOT NULL COMMENT '로그인 이메일. 앞뒤 공백 제거와 소문자 정규화를 거친 값을 저장한다. 악센트를 구분하는 콜레이션을 쓴다';
